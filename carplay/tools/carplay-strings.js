// Writes app/src/main/res/values*/carplay_strings.xml: every CarPlay-library string that names DiPlay,
// re-worded for Open Headunit, in every language the library has. From the repo root:
//   node carplay/tools/carplay-strings.js carplay/ui/src/main/res app/src/main/res
const fs = require('fs'), path = require('path');
const [libRes, appRes] = process.argv.slice(2);
const OUT = 'carplay_strings.xml';
const special = { diplay: 'Apple CarPlay' };
const specialEnglish = { back_to_diplay: 'Back to home' };

/** Names the app already defines in this folder win over the library's anyway, and may not be defined twice. */
function appNames(dir) {
  const names = new Set();
  if (!fs.existsSync(dir)) return names;
  for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.xml') && f !== OUT)) {
    for (const m of fs.readFileSync(path.join(dir, f), 'utf8').matchAll(/<string\s+name="([^"]+)"/g)) names.add(m[1]);
  }
  return names;
}

let total = 0;
for (const folder of fs.readdirSync(libRes).filter(d => /^values(-|$)/.test(d)).sort()) {
  const libDir = path.join(libRes, folder);
  const appDir = path.join(appRes, folder);
  const skip = appNames(appDir);
  const english = folder === 'values';
  const seen = new Set();
  const rows = [];
  for (const f of fs.readdirSync(libDir).filter(f => f.endsWith('.xml')).sort()) {
    const s = fs.readFileSync(path.join(libDir, f), 'utf8');
    for (const m of s.matchAll(/<string\s+name="([^"]+)"([^>]*)>([\s\S]*?)<\/string>/g)) {
      const [, name, attrs, body] = m;
      const fixed = english && name in specialEnglish ? specialEnglish[name] : special[name];
      if (!/DiPlay/.test(body) && fixed === undefined) continue;
      if (seen.has(name) || skip.has(name)) continue;
      seen.add(name);
      const text = fixed !== undefined ? fixed
        : body.replace(/DiPlay's/g, 'Open Headunit\\\'s').replace(/DiPlay/g, 'Open Headunit');
      const cleanAttrs = attrs.replace(/\s*tools:[a-z]+="[^"]*"/g, '');
      rows.push(`    <string name="${name}"${cleanAttrs}>${text.replace(/(^|[^\\])'/g, "$1\\'")}</string>`);
    }
  }
  const outFile = path.join(appDir, OUT);
  if (rows.length === 0) {
    if (fs.existsSync(outFile)) fs.unlinkSync(outFile);
    continue;
  }
  fs.mkdirSync(appDir, { recursive: true });
  fs.writeFileSync(outFile, `<?xml version="1.0" encoding="utf-8"?>
<!--
    Generated by carplay/tools/carplay-strings.js from carplay/ui's strings. The CarPlay library is DiPlay;
    every string of it that names DiPlay is re-worded here so the car never shows that name. The app's
    resources win over the library's, so these replace the originals in the APK.
-->
<resources>
${rows.join('\n')}
</resources>
`);
  total += rows.length;
  console.log(folder, rows.length);
}
console.log(total, 'strings in all');
